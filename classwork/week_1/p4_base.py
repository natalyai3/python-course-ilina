# ============================================================
# Задача 2.1. Площадь круга
# ============================================================
# Запросите радиус (вещественное число).
# Выведите площадь круга и длину окружности с точностью
# до двух знаков.
#
# Пример:
#   In: 3.0
#   Out: S = 28.27, C = 18.85
#
# Подсказка: используйте math.pi и f-строки.

import math
r = float(input("Введите радиус: "))
S = math.pi * r ** 2
C = 2 * math.pi * r
print(f"Площадь круга: {S:.2f}. Длина окружности: {C:.2f}")

