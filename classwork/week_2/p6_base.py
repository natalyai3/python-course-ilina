# Проверьте, что строка — дата вида YYYY-MM-DD.
# s = "2026-10-05"
# ok = ???  # -> true

def task_6_2(s):
    date = re.findall(r"\d+", s)
    if len(date) == 3:
        if int(date[1]) <= 12 and int(date[2]) <= 31:
            print(True)
        else:
            print(False)
    else:
        print(False)

